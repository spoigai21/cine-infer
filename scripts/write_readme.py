def md(header, rows):
    esc = lambda x: str(x).replace("|", "\\|")
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
                     + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def build_tables():
    tb = {}
    t = load("test.csv")
    t = t[t.scheme == "user"]
    g = t.groupby("model")
    med = g[["ndcg@10", "recall@10", "auc", "coverage"]].median()
    seeds = g.seed.nunique()
    order = ["two_stage", "two_tower", "ease", "ease_recent", "implicit_als", "item_knn", "most_popular"]
    tb["headline"] = md(["Model", "NDCG@10", "Recall@10 (capped)", "AUC", "Coverage", "Runs"],
                        [[NAMES[m], f4(med.loc[m, "ndcg@10"]), f4(med.loc[m, "recall@10"]),
                          f3(med.loc[m, "auc"]), pct(med.loc[m, "coverage"]),
                          "3 (median)" if seeds[m] > 1 else "deterministic"] for m in order])
    abl = ["two_stage_with_time", "two_stage", "two_stage_no_ease", "two_tower"]
    gaps = load("test_gaps.csv")
    gap = lambda a, b: gaps[(gaps.a == a) & (gaps.b == b) & (gaps.metric == "ndcg@10")].iloc[0]
    def vs(m):
        if m == "two_stage":
            return "—"
        a, b, s = (m, "two_stage", 1) if m != "two_tower" else ("two_stage", "two_tower", -1)
        r = gap(a, b)
        lo, hi = sorted([s * r.ci_low, s * r.ci_high])
        return f"{sgn(s * r['diff'])} [{sgn(lo)}, {sgn(hi)}]"
    tb["ablation"] = md(["System (test)", "NDCG@10", "vs headline (95% CI)"],
                        [[NAMES[m], f4(med.loc[m, "ndcg@10"]), vs(m)] for m in abl])

    tbd = load("analysis/test_by_boundary.csv").set_index(["model", "boundary"])
    bmodels = ["ease", "ease_recent", "two_tower", "two_stage"]
    cols = [("same_second", "same second"), ("within_1h", "within 1 h"), ("over_1h", "over 1 h"), ("all", "all")]
    users = [f"{int(tbd.loc[('ease', b), 'users']):,}" for b, _ in cols]
    tb["boundary"] = md(["Test NDCG@10 by gap between last train/val rating and first test rating"]
                        + [f"{lbl} ({u} users)" for (b, lbl), u in zip(cols, users)],
                        [[NAMES[m]] + [f4(tbd.loc[(m, b), "ndcg@10"]) for b, _ in cols] for m in bmodels])

    sc = load("split_comparison.csv").set_index("scheme")
    lbl = {"random": "Random 80/10/10", "user": "Per-user time split (the project's)",
           "global": "Global time cutoff"}
    tb["splits"] = md(["Split (EASE, same config)", "Test users", "NDCG@10 (95% CI)", "× global"],
                      [[lbl[s], f"{int(sc.loc[s, 'n_users']):,}",
                        f"{f4(sc.loc[s, 'ndcg@10'])} ({f4(sc.loc[s, 'ndcg_ci_low'])}–{f4(sc.loc[s, 'ndcg_ci_high'])})",
                        f"{sc.loc[s, 'ratio_vs_global']:.2f}"] for s in ("random", "user", "global")])

    pr = load("predictions.csv").set_index("id")
    st = load("predictions_status.csv").set_index("id")
    mark = {"confirmed": "✅ confirmed", "refuted": "❌ refuted"}
    tb["predictions"] = md(["#", "Prediction (committed before training)", "Verdict", "Evidence"],
                           [[i, pr.loc[i, "prediction"], mark.get(st.loc[i, "verdict"], st.loc[i, "verdict"]),
                             st.loc[i, "evidence"]] for i in pr.index])

    bm = load("benchmark.csv").set_index(["size", "engine"])
    tb["benchmark"] = md(["Rows", "pandas", "Spark (6 cores)", "Polars", "DuckDB"],
                         [[f"{int(bm.loc[(s, 'pandas'), 'rows']):,}"] +
                          [f"{bm.loc[(s, e), 'with_startup_s']:.2f} / {bm.loc[(s, e), 'warm_compute_s']:.2f} s"
                           for e in ("pandas", "spark", "polars", "duckdb")] for s in ("1M", "5M", "25M")])

    rows = []
    for f in ("baselines.csv", "two_tower.csv", "two_stage.csv"):
        d = load(f)
        for m in d.model.unique():
            r = d[d.model == m]
            if m.startswith("two_stage_"):
                continue
            cfg = json.loads(r.config.iloc[0])
            cfg = {k: v for k, v in cfg.items() if k not in ("device", "features", "max_iter", "batch",
                                                                "hidden", "n_uniform", "strict_time")}
            trials = int(r.n_trials.iloc[0]) if "n_trials" in r and pd.notna(r.n_trials.iloc[0]) else "—"
            secs = r.tuning_seconds.iloc[0] if "tuning_seconds" in r else float("nan")
            hours = ("—" if pd.isna(secs) else f"{secs / 3600:.1f} h" if secs >= 3600
                     else f"{secs / 60:.0f} min" if secs >= 60 else f"{secs:.0f} s")
            rows.append([NAMES.get(m, m), f4(r["ndcg@10"].median()),
                         ", ".join(f"{k}={v}" for k, v in cfg.items()) or "—", trials, hours])
    tb["tuning"] = md(["Model", "Validation NDCG@10", "Chosen config", "Trials", "Tuning time"], rows)
    return tb


# ---------------------------------------------------------------------------------------------

def render(template_text):
    check_claims()
    values, tables = build_values(), build_tables()
    unknown = []

    def sub(m):
        key = m.group(1)
        if key.startswith("table:"):
            name = key[len("table:"):]
            if name in tables:
                return tables[name]
        elif key in values:
            return values[key]
        unknown.append(key)
        return m.group(0)

    out = PLACEHOLDER.sub(sub, template_text)
    if unknown:
        raise KeyError(f"unknown placeholders in {TEMPLATE.name}: {sorted(set(unknown))}")
    return HEADER + out


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    a = p.parse_args(argv)
    fresh = render(TEMPLATE.read_text())
    if a.check:
        current = README.read_text() if README.exists() else ""
        if current != fresh:
            diff = difflib.unified_diff(current.splitlines(), fresh.splitlines(),
                                        "README.md (committed)", "README.md (from results)", lineterm="", n=0)
            print("README.md is out of date with results/*.csv (run `make readme`):")
            print("\n".join(list(diff)[:60]))
            sys.exit(1)
        print("README.md matches results/*.csv")
        return
    README.write_text(fresh)
    print(f"wrote {README.name}")


if __name__ == "__main__":
    main()
