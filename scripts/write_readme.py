"""Phase 10: render README.md from README.template.md, with every number read from results/.

The template is hand-written prose with placeholders:
  {{name}}        a single value (see build_values), e.g. {{test.two_stage.ndcg}}
  {{table:name}}  a whole markdown table (see build_tables), e.g. {{table:headline}}
An unknown placeholder is an error, never a blank. Only committed files are read (results/*.csv),
so `--check` works in CI without the dataset.

  python -m scripts.write_readme           write README.md
  python -m scripts.write_readme --check   exit 1 (with a diff) if README.md is stale
"""
import argparse
import difflib
import json
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
TEMPLATE = ROOT / "README.template.md"
README = ROOT / "README.md"
HEADER = ("<!-- Generated by scripts/write_readme.py from README.template.md and results/*.csv.\n"
          "     Edit the template, then run `make readme`. `make readme-check` (also in CI) fails\n"
          "     if this file and the results disagree. -->\n")
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.:@\-]+)\s*\}\}")

NAMES = {"most_popular": "Most-popular", "item_knn": "Item-kNN", "implicit_als": "Implicit ALS",
         "ease": "EASE", "ease_recent": "EASE, recent-10 input (control)",
         "two_tower": "Two-tower (retrieval)", "two_stage": "**Two-stage (headline)**",
         "two_stage_no_ease": "Two-stage without EASE features (ablation)",
         "two_stage_with_time": "Two-stage + time features (ablation, not used)"}


def f3(x):
    return f"{x:.3f}"


def f4(x):
    return f"{x:.4f}"


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def sgn(x, d=4):
    return f"{x:+.{d}f}"


def load(name):
    return pd.read_csv(RESULTS / name)


def stat_table(name):
    d = load(name)
    return {(r.scheme, r.stat): r.value for r in d.itertuples()}


