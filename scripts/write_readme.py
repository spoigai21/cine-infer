# Claims: prose statements in the template that depend on the data. If a result changes so a
# claim no longer holds, rendering fails instead of silently publishing a false sentence.
# ---------------------------------------------------------------------------------------------

def check_claims():
    tb = load("analysis/test_by_boundary.csv").set_index(["model", "boundary"])["ndcg@10"]
    bm = load("benchmark.csv").set_index(["size", "engine"])
    claims = {
        "two-tower beats EASE within a session":
            tb[("two_tower", "same_second")] > tb[("ease", "same_second")],
        "two-tower is worse than EASE when test starts > 1 h later":
            tb[("two_tower", "over_1h")] < tb[("ease", "over_1h")],
        "recent-10 EASE doesn't reproduce the two-tower's within-session score":
            tb[("ease_recent", "same_second")] < tb[("two_tower", "same_second")],
        "two-stage beats EASE in every boundary bucket":
            all(tb[("two_stage", b)] > tb[("ease", b)] for b in ("same_second", "within_1h", "over_1h", "all")),
        "DuckDB and Polars beat pandas and Spark at every size, both timings":
            all(bm.loc[(s, fast), col] < bm.loc[(s, slow), col]
                for s in ("1M", "5M", "25M") for fast in ("duckdb", "polars")
                for slow in ("pandas", "spark") for col in ("with_startup_s", "warm_compute_s")),
        "Spark wins at 25M, pandas at 1M and 5M (with startup)":
            bm.loc[("25M", "spark"), "with_startup_s"] < bm.loc[("25M", "pandas"), "with_startup_s"]
            and all(bm.loc[(s, "pandas"), "with_startup_s"] < bm.loc[(s, "spark"), "with_startup_s"]
                    for s in ("1M", "5M")),
    }
    g = load("test_gaps.csv").set_index(["a", "b", "metric"])
    claims["removing EASE features hurts the ranker significantly"] = \
        g.loc[("two_stage_no_ease", "two_stage", "ndcg@10"), "ci_high"] < 0
    claims["time features would help (so excluding them is a real cost)"] = \
        g.loc[("two_stage_with_time", "two_stage", "ndcg@10"), "ci_low"] > 0
    pe = load("pit_experiment.csv").groupby("variant")["ci_low"].median()
    claims["point-in-time features beat the headline's (both variants, CI above 0)"] = \
        pe["pit"] > 0 and pe["pit_time"] > 0
    false = [c for c, ok in claims.items() if not ok]
    if false:
        raise AssertionError(f"README claims no longer supported by results: {false}")


