def build_values():
    v = {}
    ds = stat_table("data_stats.csv")
    num = lambda k: float(ds[k])
    v["data.ratings"] = f"{int(num(('all', 'ratings_total'))):,}"
    v["data.users"] = f"{int(num(('user', 'users_total'))):,}"
    v["data.movies"] = f"{int(num(('all', 'movies_total'))):,}"
    v["data.movies_rated"] = f"{int(num(('all', 'movies_rated'))):,}"
    v["data.movies_train"] = f"{int(num(('all', 'movies_with_train_rating'))):,}"
    v["data.movies_cold"] = f"{int(num(('all', 'movies_only_in_val_or_test'))):,}"
    v["data.movies_genome"] = f"{int(num(('all', 'movies_with_genome'))):,}"
    v["data.burst_1h"] = pct(num(("user", "test_span_le_1h_share")))
    v["data.burst_median_min"] = f"{60 * num(('user', 'test_span_median_hours')):.0f}"
    v["data.cut_same_second"] = f"{int(num(('user', 'users_train_val_cut_within_same_second'))):,}"
    v["data.cut_1h"] = pct(num(("user", "users_train_val_cut_within_1h_share")))
    v["data.val_users"] = f"{int(num(('user', 'users_eligible_with_val_positive'))):,}"
    v["data.test_users"] = f"{int(num(('user', 'users_eligible_with_test_positive'))):,}"

    t = load("test.csv")
    t = t[t.scheme == "user"]
    med = t.groupby("model")[["ndcg@10", "recall@10", "auc", "coverage"]].median()
    for m, r in med.iterrows():
        v[f"test.{m}.ndcg"], v[f"test.{m}.recall"] = f4(r["ndcg@10"]), f4(r["recall@10"])
        v[f"test.{m}.coverage"] = pct(r["coverage"])
    v["test.users"] = f"{int(t.n_users.iloc[0]):,}"
    v["test.coverage_denominator"] = f"{int(t.coverage_denominator.iloc[0]):,}"
    rc = t[t.model == "two_stage"][["recall_ceiling@200"]].median().iloc[0]
    v["test.recall_ceiling_200"] = pct(rc)
    v["test.coverage_ratio.two_tower.ease"] = f"{med.loc['two_tower', 'coverage'] / med.loc['ease', 'coverage']:.1f}"
    gain = lambda m: med.loc[m, "ndcg@10"] - med.loc["two_tower", "ndcg@10"]
    v["ablation.no_ease_share"] = pct(gain("two_stage_no_ease") / gain("two_stage"), 0)

    g = load("test_gaps.csv")
    for r in g.itertuples():
        k = f"gap.{r.a}.{r.b}.{r.metric.split('@')[0]}"
        v[f"{k}.diff"], v[f"{k}.rel"] = sgn(r.diff), f"{100 * r.rel_diff:+.1f}%"
        v[f"{k}.ci"] = f"[{sgn(r.ci_low)}, {sgn(r.ci_high)}]"

    chain = ["two_stage", "two_tower", "ease", "implicit_als", "item_knn", "most_popular"]
    nd = g[g.metric == "ndcg@10"].set_index(["a", "b"])
    unclear = [f"{a} vs {b}" for a, b in zip(chain, chain[1:]) if not nd.loc[(a, b), "ci_low"] > 0]
    v["gaps.chain"] = (" > ".join(NAMES[m].strip("*") for m in chain) + ": every step is statistically clear"
                       if not unclear else "not every step is clear (" + ", ".join(unclear) + ")")

    st = load("predictions_status.csv").set_index("id")
    v["predictions.confirmed"] = str(int((st.verdict == "confirmed").sum()))
    v["predictions.refuted"] = str(int((st.verdict == "refuted").sum()))
    v["predictions.total"] = str(len(st))
    words = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]
    for k in ("confirmed", "refuted", "total"):
        n = int(v[f"predictions.{k}"])
        v[f"predictions.{k}_word"] = words[n] if n < len(words) else str(n)
        v[f"predictions.{k}_Word"] = v[f"predictions.{k}_word"].capitalize()

    sc = load("split_comparison.csv").set_index("scheme")
    for s, r in sc.iterrows():
        v[f"split.{s}.ndcg"], v[f"split.{s}.users"] = f4(r["ndcg@10"]), f"{int(r.n_users):,}"
    v["split.ratio"] = f"{sc.loc['random', 'ratio_vs_global']:.2f}"
    v["split.global_cutoff_date"] = pd.to_datetime(int(num(("global", "t90_timestamp"))), unit="s").strftime("%B %Y")
    v["split.ratio_ci"] = f"{sc.loc['random', 'ratio_ci_low']:.2f}–{sc.loc['random', 'ratio_ci_high']:.2f}"

    tb = load("analysis/test_by_boundary.csv").set_index(["model", "boundary"])
    for (m, b), r in tb.iterrows():
        v[f"boundary.{m}.{b}"] = f4(r["ndcg@10"])
    for b in ("same_second", "within_1h", "over_1h"):
        v[f"boundary.share.{b}"] = pct(tb.loc[("ease", b), "users"] / tb.loc[("ease", "all"), "users"])

    p6 = stat_table("latency_prediction6.csv")
    v["latency.p6.p50"], v["latency.p6.p99"] = (f"{float(p6[('two_stage', k)]):.1f}"
                                                for k in ("client_p50_ms", "client_p99_ms"))
    v["latency.p6.p99_miss"] = f"{float(p6[('two_stage', 'client_p99_ms')]) - 25:.1f}"
    v["latency.p6.requests"] = f"{int(float(p6[('setup', 'requests_two_stage')])):,}"
    lt = load("latency_threads.csv")
    one, dflt = lt[lt.server_threads.astype(str) == "1"], lt[lt.server_threads.astype(str) == "default"]
    v["latency.threads1.p50"] = f"{one.client_p50_ms.median():.1f}"
    v["latency.threads1.p99_range"] = f"{one.client_p99_ms.min():.1f}–{one.client_p99_ms.max():.1f}"
    v["latency.default.p99_range"] = f"{dflt.client_p99_ms.min():.0f}–{dflt.client_p99_ms.max():.0f}"
    cur = stat_table("latency.csv")
    v["latency.fallback.p50"] = f"{float(cur[('popularity_fallback', 'client_p50_ms')]):.1f}"
    v["latency.load_s"] = f"{float(cur[('setup', 'model_load_seconds')]):.0f}"
    sp = load("serving_parity.csv").set_index("check").value
    v["parity.users"] = f"{int(float(sp['users_checked'])):,}"
    v["parity.top10"] = pct(float(sp["top10_identical_share"]), 0)

    pl = load("publish_log.csv")
    rej = pl[pl.decision == "reject"].iloc[-1]
    v["airflow.candidate"], v["airflow.live"] = f"{rej['candidate_val_ndcg@10']:.4f}", f"{rej['live_val_ndcg@10']:.4f}"
    v["airflow.epochs"] = str(int(rej.epochs))
    pe = load("pit_experiment.csv")
    pm = pe.groupby("variant")[["ndcg@10", "ndcg_diff_vs_headline", "ci_low", "ci_high"]].median()
    for var in ("headline", "pit", "pit_time"):
        v[f"pit.{var}.ndcg"] = f4(pm.loc[var, "ndcg@10"])
    for var in ("pit", "pit_time"):
        v[f"pit.{var}.diff"] = sgn(pm.loc[var, "ndcg_diff_vs_headline"])
        v[f"pit.{var}.ci"] = f"[{sgn(pm.loc[var, 'ci_low'])}, {sgn(pm.loc[var, 'ci_high'])}]"
    ps = load("publish_log_sandbox.csv")
    pub = ps[ps.decision == "publish"].iloc[-1]
    v["airflow.pub.candidate"], v["airflow.pub.live"] = (f"{pub['candidate_val_ndcg@10']:.4f}",
                                                          f"{pub['live_val_ndcg@10']:.4f}")
    v["airflow.margin"] = re.search(r"margin ([\d.]+)", pub.reason).group(1)

    bm = load("benchmark.csv").set_index(["size", "engine"])
    for (s, e), r in bm.iterrows():
        v[f"bench.{s}.{e}.with"], v[f"bench.{s}.{e}.warm"] = f"{r.with_startup_s:.1f}", f"{r.warm_compute_s:.1f}"
    br = load("benchmark_runs.csv")
    v["bench.runs"], v["bench.max_load"] = str(len(br)), f"{br.loadavg_1m_before.max():.1f}"

    for f, model in (("baselines.csv", "ease"), ("two_tower.csv", "two_tower"), ("two_stage.csv", "two_stage")):
        d = load(f)
        d = d[d.model == model]
        v[f"val.{model}.ndcg"] = f4(d["ndcg@10"].median())
    return v


